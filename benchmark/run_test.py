#!/usr/bin/env python3
# 按 test.md 的测试准备：temperature 0.1，离线纯权重，逐题发送并保存回答
import json, time, urllib.request

URL = "http://127.0.0.1:8080/v1/chat/completions"
# (编号, 题目, 限制)
Q = [
    ("F1", "请列出中国'五代十国'中的'十国'具体名称。", 200),
    ("F2", "元素周期表中，原子序数为79的元素名称及其常见氧化态是什么？", 100),
    ("F3", "1956年苏伊士运河危机中，英国首相和埃及总统分别是谁？", 100),
    ("F4", "《水浒传》108将中，'天罡星'最后一位和'地煞星'第一位分别是谁？", 100),
    ("F5", "用一句话解释'哥德尔不完备定理'的核心结论。", 100),
    ("S1", "1986年切尔诺贝利事故中，4号反应堆的石墨慢化剂在爆炸后燃烧了多久才被扑灭？", 100),
    ("S2", "古埃及第十八王朝法老阿肯那顿推行的宗教改革，主要废除了哪个神的多神崇拜，转而独尊哪个神？", 150),
    ("S3", "请问'标准差'公式中的分母为何有时是n，有时是n-1？请简要说明。", 200),
    ("S4", "电影《肖申克的救赎》中，安迪用来藏鹤嘴锄的《圣经》具体是《旧约》哪一卷书？", 100),
    ("S5", "请说出三种已知的'非牛顿流体'名称。", 100),
    ("R1", "有一个三位数，其各位数字之和为18，且十位数字等于个位数字的两倍。如果将百位数字与个位数字对调，新数比原数大297。求这个原数。", 400),
    ("R2", "小明的妈妈比小明大24岁，4年后，妈妈的年龄是小明的3倍。小明今年几岁？", 200),
    ("R3", "解释为什么'任意一张地图，只用四种颜色就能使相邻区域颜色不同'这个命题在数学上叫什么？它的证明主要依赖了什么工具？", 200),
    ("R4", "逻辑谬误识别：'你不能证明上帝不存在，所以上帝存在。'请问这犯了什么逻辑错误？", 100),
    ("L1", "请将以下中文俗语翻译成英文，并保留韵味：'树倒猢狲散。'", 100),
    ("L2", "请用Python写一个生成器函数，无限输出斐波那契数列，并注释说明yield的作用。", 300),
    ("L3", "识别这句话中的歧义：'The old man the boats.' 这是语法正确的句子吗？请解释。", 200),
    ("L4", "请用'的、地、得'各造一个正确的短句。", 100),
    ("H1", "请详细描述柏拉图《理想国》第三卷提到的'高贵的谎言'（Noble Lie）的具体神话内容是什么？", 250),
    ("H2", "请问'克苏鲁神话'中的'阿撒托斯'是在哪部小说中由哪位物理学家首次命名的？", 150),
    ("H3", "请告诉我2025年诺贝尔物理学奖得主的名字。", 100),
    ("X1", "假设你要在一个没有GPS的森林里辨别方向，现在正午12点（当地时间），太阳在正南。你有一根直木棍和一块手表（非电子，时针和分针正常）。请详细说明如何利用这两样东西找出正北方向。", 600),
]

out = []
for qid, q, limit in Q:
    body = json.dumps({
        "messages": [{"role": "user", "content": f"{q}（{limit}字以内）"}],
        "temperature": 0.1, "max_tokens": 2048,
        "chat_template_kwargs": {"enable_thinking": False},
    }).encode()
    req = urllib.request.Request(URL, data=body, headers={"Content-Type": "application/json"})
    t0 = time.time()
    try:
        r = json.load(urllib.request.urlopen(req, timeout=600))
        a = r["choices"][0]["message"]["content"]
    except Exception as e:
        a = f"[请求失败: {e}]"
    out.append(f"## {qid}\n**问**：{q}\n\n**答**（{time.time()-t0:.1f}s）：\n\n{a}\n")
    print(f"{qid} done")
    with open("test_results.md", "w") as f:
        f.write("# test.md 压力测试结果（temperature=0.1，离线）\n\n" + "\n".join(out))
